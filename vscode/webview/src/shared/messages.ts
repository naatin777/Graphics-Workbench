type WebviewMessageKey = (typeof WEBVIEW_MESSAGE_KEYS)[number];
export type MessageReader = (key: WebviewMessageKey) => string;

export function createMessageReader(catalog: MessageCatalog): MessageReader {
  return (key) => {
    const value = catalog[key];
    if (value === undefined) {
      throw new Error(`Webview message "${key}" was not provided.`);
    }
    return value;
  };
}
